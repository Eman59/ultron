#!/bin/bash
# ═══════════════════════════════════════════════════════════════════
# ULTRON SELF-LEARNING SYSTEM — Quick Start
# ═══════════════════════════════════════════════════════════════════
#
# This script brings up the entire self-learning stack:
#   1. Local LLM (Ollama with DeepSeek Coder)
#   2. Learning Service (experience, patterns, optimization)
#   3. Infrastructure (Redis, Qdrant for vector search)
#   4. Bootstrap (seeds initial data)
#
# Usage:
#   ./start_learning.sh              # Start everything
#   ./start_learning.sh --local-only # Only use local LLM (no API keys needed)
#   ./start_learning.sh --stop       # Stop everything
#
# Prerequisites:
#   - Docker and Docker Compose
#   - (Optional) OPENAI_API_KEY or ANTHROPIC_API_KEY for cloud LLM
#
# ═══════════════════════════════════════════════════════════════════

set -e

PROJECT_ROOT="$(cd "$(dirname "$0")" && pwd)"
DOCKER_DIR="$PROJECT_ROOT/docker"

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m'

print_banner() {
    echo ""
    echo -e "${RED}  ╔══════════════════════════════════════════════════════════╗${NC}"
    echo -e "${RED}  ║         ULTRON SELF-LEARNING SYSTEM                     ║${NC}"
    echo -e "${RED}  ║         Autonomous Code Evolution Engine                ║${NC}"
    echo -e "${RED}  ╚══════════════════════════════════════════════════════════╝${NC}"
    echo ""
}

# Handle --stop
if [ "$1" = "--stop" ]; then
    echo -e "${YELLOW}Stopping Ultron self-learning stack...${NC}"
    cd "$DOCKER_DIR" && docker compose down
    echo -e "${GREEN}Stopped.${NC}"
    exit 0
fi

print_banner

# Check Docker
if ! command -v docker &> /dev/null; then
    echo -e "${RED}ERROR: Docker is not installed.${NC}"
    echo "Install Docker: https://docs.docker.com/get-docker/"
    exit 1
fi

if ! docker info &> /dev/null 2>&1; then
    echo -e "${RED}ERROR: Docker daemon is not running.${NC}"
    exit 1
fi

# Check for API keys
echo -e "${BLUE}Checking LLM configuration...${NC}"

if [ "$1" = "--local-only" ]; then
    echo -e "  ${YELLOW}Local-only mode: Using Ollama (no API keys required)${NC}"
    export ULTRON_PREFER_LOCAL_LLM=true
else
    if [ -n "$OPENAI_API_KEY" ]; then
        echo -e "  ${GREEN}✓ OpenAI API key found${NC}"
    fi
    if [ -n "$ANTHROPIC_API_KEY" ]; then
        echo -e "  ${GREEN}✓ Anthropic API key found${NC}"
    fi
    if [ -n "$DEEPSEEK_API_KEY" ]; then
        echo -e "  ${GREEN}✓ DeepSeek API key found${NC}"
    fi
    if [ -n "$GROQ_API_KEY" ]; then
        echo -e "  ${GREEN}✓ Groq API key found${NC}"
    fi
    if [ -z "$OPENAI_API_KEY" ] && [ -z "$ANTHROPIC_API_KEY" ] && [ -z "$DEEPSEEK_API_KEY" ]; then
        echo -e "  ${YELLOW}No cloud API keys found — will use local Ollama only${NC}"
        echo -e "  ${YELLOW}Set OPENAI_API_KEY or ANTHROPIC_API_KEY for better intelligence${NC}"
    fi
fi

# Create .env file for docker compose
ENV_FILE="$DOCKER_DIR/.env"
cat > "$ENV_FILE" << EOF
# Ultron Self-Learning Environment
# Generated by start_learning.sh at $(date)
OPENAI_API_KEY=${OPENAI_API_KEY:-}
ANTHROPIC_API_KEY=${ANTHROPIC_API_KEY:-}
DEEPSEEK_API_KEY=${DEEPSEEK_API_KEY:-}
GROQ_API_KEY=${GROQ_API_KEY:-}
EOF

# Start the stack
echo ""
echo -e "${BLUE}Starting Ultron self-learning stack...${NC}"
echo ""

cd "$DOCKER_DIR"

# Start infrastructure first
echo -e "  ${BLUE}[1/4] Starting infrastructure (Redis, Qdrant)...${NC}"
docker compose up -d redis qdrant 2>/dev/null

# Wait for infra
sleep 3

# Start Ollama (local LLM)
echo -e "  ${BLUE}[2/4] Starting local LLM (Ollama)...${NC}"
docker compose up -d ollama 2>/dev/null
sleep 2

# Pull the model (background)
echo -e "  ${BLUE}[3/4] Pulling AI model (background, may take a few minutes first time)...${NC}"
docker compose up -d ollama-init 2>/dev/null

# Start the learning service
echo -e "  ${BLUE}[4/4] Starting Learning Service...${NC}"
docker compose up -d learning-service 2>/dev/null

# Wait and check health
echo ""
echo -e "${BLUE}Waiting for services to be ready...${NC}"
sleep 5

# Check status
LEARNING_HEALTHY=$(docker inspect --format='{{.State.Running}}' ultron-learning 2>/dev/null || echo "false")
OLLAMA_HEALTHY=$(docker inspect --format='{{.State.Running}}' ultron-ollama 2>/dev/null || echo "false")
REDIS_HEALTHY=$(docker inspect --format='{{.State.Running}}' ultron-redis 2>/dev/null || echo "false")

echo ""
echo -e "${GREEN}═══════════════════════════════════════════════════════════${NC}"
echo -e "${GREEN}  ULTRON SELF-LEARNING SYSTEM — STATUS${NC}"
echo -e "${GREEN}═══════════════════════════════════════════════════════════${NC}"
echo ""

if [ "$REDIS_HEALTHY" = "true" ]; then
    echo -e "  ${GREEN}✓ Redis${NC}            — Running (port 6379)"
else
    echo -e "  ${RED}✗ Redis${NC}            — Not running"
fi

if [ "$OLLAMA_HEALTHY" = "true" ]; then
    echo -e "  ${GREEN}✓ Ollama (LLM)${NC}    — Running (port 11434)"
else
    echo -e "  ${YELLOW}⟳ Ollama (LLM)${NC}    — Starting..."
fi

if [ "$LEARNING_HEALTHY" = "true" ]; then
    echo -e "  ${GREEN}✓ Learning Service${NC} — Running (gRPC: 50060, JSON: 50061)"
else
    echo -e "  ${YELLOW}⟳ Learning Service${NC} — Starting..."
fi

echo ""
echo -e "${BLUE}Endpoints:${NC}"
echo "  Learning gRPC:  localhost:50060"
echo "  Learning JSON:  localhost:50061"
echo "  Ollama API:     localhost:11434"
echo "  Redis:          localhost:6379"
echo ""
echo -e "${BLUE}Useful commands:${NC}"
echo "  View logs:      docker logs -f ultron-learning"
echo "  System status:  curl localhost:50061 -d '{\"method\":\"get_status\",\"params\":{}}'"
echo "  List files:     curl localhost:50061 -d '{\"method\":\"list_dir\",\"params\":{\"path\":\"python\"}}'"
echo "  Search code:    curl localhost:50061 -d '{\"method\":\"search_code\",\"params\":{\"pattern\":\"def improve\"}}'"
echo "  Stop:           ./start_learning.sh --stop"
echo ""
echo -e "${GREEN}The self-learning system is now active and evolving.${NC}"
echo ""
